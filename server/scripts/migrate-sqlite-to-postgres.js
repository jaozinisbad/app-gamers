const path = require('path');
const { DatabaseSync } = require('node:sqlite');
const { Client } = require('pg');

const sqlitePath = process.env.SQLITE_DATABASE_PATH || path.join(__dirname, '..', 'app-gamers.db');

const schema = `
CREATE TABLE usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  senha_hash TEXT NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  avatar_cor TEXT NOT NULL DEFAULT '#5865f2',
  status TEXT NOT NULL DEFAULT 'Disponível',
  avatar_url TEXT,
  banner_url TEXT
);
CREATE TABLE servidores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  dono_id BIGINT NOT NULL REFERENCES usuarios(id),
  codigo_convite TEXT NOT NULL UNIQUE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  icone_url TEXT,
  banner_url TEXT,
  descricao TEXT
);
CREATE TABLE membros_servidor (
  servidor_id BIGINT NOT NULL REFERENCES servidores(id) ON DELETE CASCADE,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  papel TEXT NOT NULL DEFAULT 'membro',
  entrou_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (servidor_id, usuario_id)
);
CREATE TABLE canais (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  servidor_id BIGINT NOT NULL REFERENCES servidores(id) ON DELETE CASCADE,
  nome TEXT NOT NULL,
  tipo TEXT NOT NULL CHECK (tipo IN ('texto', 'voz')),
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE mensagens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  canal_id BIGINT NOT NULL REFERENCES canais(id) ON DELETE CASCADE,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
  conteudo TEXT NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  anexo_nome TEXT,
  anexo_tipo TEXT,
  anexo_url TEXT,
  anexo_tamanho BIGINT
);
CREATE TABLE cargos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  servidor_id BIGINT NOT NULL REFERENCES servidores(id) ON DELETE CASCADE,
  nome TEXT NOT NULL,
  cor TEXT NOT NULL DEFAULT '#99aab5',
  permissoes JSONB NOT NULL DEFAULT '{}'::jsonb,
  posicao INTEGER NOT NULL DEFAULT 0,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE membros_cargos (
  cargo_id BIGINT NOT NULL REFERENCES cargos(id) ON DELETE CASCADE,
  servidor_id BIGINT NOT NULL REFERENCES servidores(id) ON DELETE CASCADE,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  PRIMARY KEY (cargo_id, usuario_id)
);
CREATE TABLE banimentos_servidor (
  servidor_id BIGINT NOT NULL REFERENCES servidores(id) ON DELETE CASCADE,
  usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (servidor_id, usuario_id)
);
CREATE TABLE mensagens_diretas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  remetente_id BIGINT NOT NULL REFERENCES usuarios(id),
  destinatario_id BIGINT NOT NULL REFERENCES usuarios(id),
  conteudo TEXT NOT NULL,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX mensagens_canal_id_idx ON mensagens(canal_id, id);
CREATE INDEX membros_servidor_usuario_id_idx ON membros_servidor(usuario_id);
`;

const tables = [
  ['usuarios', ['id', 'nome', 'email', 'senha_hash', 'criado_em', 'avatar_cor', 'status', 'avatar_url', 'banner_url']],
  ['servidores', ['id', 'nome', 'dono_id', 'codigo_convite', 'criado_em', 'icone_url', 'banner_url', 'descricao']],
  ['membros_servidor', ['servidor_id', 'usuario_id', 'papel', 'entrou_em']],
  ['canais', ['id', 'servidor_id', 'nome', 'tipo', 'criado_em']],
  ['mensagens', ['id', 'canal_id', 'usuario_id', 'conteudo', 'criado_em', 'anexo_nome', 'anexo_tipo', 'anexo_url', 'anexo_tamanho']],
  ['cargos', ['id', 'servidor_id', 'nome', 'cor', 'permissoes', 'posicao', 'criado_em']],
  ['membros_cargos', ['cargo_id', 'servidor_id', 'usuario_id']],
  ['banimentos_servidor', ['servidor_id', 'usuario_id', 'criado_em']],
  ['mensagens_diretas', ['id', 'remetente_id', 'destinatario_id', 'conteudo', 'criado_em']],
];

async function main() {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL é obrigatório.');
  if (process.env.ALLOW_DESTRUCTIVE_MIGRATION !== '1') {
    throw new Error('Migração interrompida: confirme que o destino é uma branch Neon descartável definindo ALLOW_DESTRUCTIVE_MIGRATION=1.');
  }
  const sqlite = new DatabaseSync(sqlitePath, { readOnly: true });
  const postgres = new Client({ connectionString: process.env.DATABASE_URL });
  await postgres.connect();
  try {
    await postgres.query('BEGIN');
    await postgres.query('DROP SCHEMA public CASCADE; CREATE SCHEMA public;');
    await postgres.query(schema);
    for (const [table, columns] of tables) {
      const rows = sqlite.prepare(`SELECT ${columns.join(', ')} FROM ${table}`).all();
      for (const row of rows) {
        const values = columns.map((column) => column === 'permissoes' ? JSON.parse(row[column] || '{}') : row[column]);
        const placeholders = columns.map((_, index) => `$${index + 1}`).join(', ');
        await postgres.query(`INSERT INTO ${table} (${columns.join(', ')}) VALUES (${placeholders})`, values);
      }
      console.log(`${table}: ${rows.length}`);
    }
    for (const table of ['usuarios', 'servidores', 'canais', 'mensagens', 'cargos', 'mensagens_diretas']) {
      await postgres.query(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), COALESCE((SELECT MAX(id) FROM ${table}), 1), true)`);
    }
    await postgres.query('COMMIT');
  } catch (error) {
    await postgres.query('ROLLBACK');
    throw error;
  } finally {
    sqlite.close();
    await postgres.end();
  }
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
